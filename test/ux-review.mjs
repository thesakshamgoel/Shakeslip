import { createRequire } from 'node:module'
const require = createRequire(new URL('../server/package.json', import.meta.url))
const { default: puppeteer } = await import(require.resolve('puppeteer-core'))
import assert from 'node:assert/strict'
const browser = await puppeteer.launch({ executablePath: '/Applications/Brave Browser.app/Contents/MacOS/Brave Browser', headless: true })
const page = await browser.newPage(), errors = []
page.on('pageerror', e => errors.push(e.message))
page.on('dialog', d => d.accept())
const wait = ms => new Promise(r => setTimeout(r, ms))
const click = async text => { const found = await page.evaluate(text => { const el = [...document.querySelectorAll('button,a')].find(x => x.textContent.trim() === text); el?.click(); return !!el }, text); assert(found, `Missing control: ${text}`); await wait(350) }
try {
  await page.setViewport({ width: 1440, height: 1000 })
  await page.goto('http://localhost:5173/login', { waitUntil: 'networkidle0' })
  await page.evaluate(async () => { localStorage.setItem('ss-cookie-ok','1'); localStorage.setItem('ss-last-seen',String(Date.now())); const demo = await (await fetch('/api/dev/demo', {method:'POST'})).json(); await fetch('/api/account/login', {method:'POST', headers:{'Content-Type':'application/json'}, body:JSON.stringify(demo.studio)}) })
  await page.goto('http://localhost:5173/studio/invoices', { waitUntil: 'networkidle0' }); await wait(2200)
  assert(await page.$('.inv-grid'), 'Invoices should default to grid')
  await page.screenshot({ path:'/tmp/shakeslip-ux-review/invoices-desktop.png', fullPage:true })
  await page.goto('http://localhost:5173/studio/clients', { waitUntil:'networkidle0' })
  assert(await page.$('.client-grid'), 'Clients should default to grid')
  await click('Connect link')
  assert(await page.$('dialog[open] a[href^="https://wa.me/"]'))
  assert(await page.$('dialog[open] a[href^="mailto:"]'))
  await page.screenshot({ path:'/tmp/shakeslip-ux-review/connect-desktop.png' })
  await page.keyboard.press('Escape'); await wait(400)
  const data = await page.evaluate(async () => ({types:await (await fetch('/api/studio/types')).json(), links:await (await fetch('/api/studio/links')).json()}))
  await page.goto(`http://localhost:5173/studio/new?type=${data.types[0].id}&client=${data.links.find(x=>x.status==='active').id}`, {waitUntil:'networkidle0'})
  await page.waitForSelector('button.ed2-step'); await wait(2000)
  await page.locator('button.ed2-step:nth-of-type(5)').click()
  await page.waitForSelector('[contenteditable="true"]', {timeout:5000})
  await page.focus('[contenteditable="true"]')
  await page.keyboard.down('Meta'); await page.keyboard.press('End'); await page.keyboard.up('Meta')
  await page.keyboard.press('Enter'); await page.keyboard.type('Browser verification paragraph with continuous typing.')
  await page.evaluate(() => { const dt = new DataTransfer(); dt.setData('text/html','<h2>Imported heading</h2><p><strong>Bold paste</strong> and <u>underlined paste</u>.</p><ul><li>List item</li></ul><script>window.badImport=true</script>'); document.querySelector('[contenteditable="true"]').dispatchEvent(new ClipboardEvent('paste',{clipboardData:dt,bubbles:true,cancelable:true})) })
  await wait(500)
  assert(await page.$('.rich-page strong'))
  assert(await page.$('.rich-page h2'), 'Pasted heading should keep its own block')
  const fileInput = await page.$('input[type=file][accept=".docx,.txt"]'); await fileInput.uploadFile('/tmp/shakeslip-ux-review/terms.docx');
  await page.waitForFunction(()=>document.querySelector('.rich-page')?.textContent.includes('Word imported bold text'))
  assert(await page.evaluate(()=>[...document.querySelectorAll('.rich-page strong')].some(x=>x.textContent.includes('Word imported bold text'))))
  assert.equal(await page.evaluate(()=>window.badImport),undefined)
  await browser.defaultBrowserContext().overridePermissions('http://localhost:5173',['clipboard-read','clipboard-sanitized-write'])
  await page.locator('.rich-toolbar button:last-of-type').click()
  await page.waitForFunction(()=>[...document.querySelectorAll('.rich-toolbar button')].some(x=>x.textContent==='Copied'))
  const copied=await page.evaluate(async()=>{const items=await navigator.clipboard.read();const html=await items.find(x=>x.types.includes('text/html')).getType('text/html');return html.text()})
  assert(copied.includes('<strong>Word imported bold text</strong>'), 'Copy should retain Word formatting')
  await click('Save as template'); await page.type('dialog[open] input', 'Browser verification template'); await click('Save template'); await wait(500)
  const templates=await page.evaluate(async()=>await(await fetch('/api/studio/document-templates')).json())
  const saved=templates.find(t=>t.name==='Browser verification template'); assert(saved?.content.startsWith('ssdoc:1:'))
  await page.waitForFunction(()=>!document.querySelector('dialog[open]'))
  await wait(1000)
  await page.screenshot({ path:'/tmp/shakeslip-ux-review/terms-desktop.png',fullPage:true })
  for (const width of [360,390,768,1024,1440]) {
    await page.setViewport({width,height:900,isMobile:width<600,hasTouch:width<600}); await wait(2400)
    await page.waitForSelector('.rich-page')
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1)
    assert(!overflow,`Horizontal overflow at ${width}`)
    if(width===390)await page.screenshot({path:'/tmp/shakeslip-ux-review/terms-phone.png',fullPage:true})
  }
  await page.emulateMediaFeatures([{name:'prefers-reduced-motion',value:'reduce'}])
  await page.evaluate(()=>{document.documentElement.dataset.theme='light'})
  await wait(500)
  await page.screenshot({path:'/tmp/shakeslip-ux-review/terms-light.png',fullPage:true})
  await page.evaluate(async id=>{await fetch(`/api/studio/document-templates/${id}`,{method:'DELETE'})},saved.id)
  await page.goto('http://localhost:5173/studio/settings?s=account',{waitUntil:'networkidle0'})
  await page.waitForSelector('.danger-zone')
  await click('Delete account')
  assert(await page.$('dialog[open] button.btn-danger:disabled'))
  await page.type('dialog[open] input','DELETE')
  assert(await page.$('dialog[open] button.btn-danger:not(:disabled)'))
  for(let i=0;i<8;i++)await page.keyboard.press('Tab')
  assert(await page.evaluate(()=>!!document.activeElement.closest('dialog[open]')))
  await page.screenshot({path:'/tmp/shakeslip-ux-review/delete-confirmation.png'})
  await page.keyboard.press('Escape')
  await page.waitForFunction(()=>!document.querySelector('dialog[open]'))
  assert.equal(await page.evaluate(()=>document.body.style.overflow),'')
  console.log(JSON.stringify({errors,screenshots:'/tmp/shakeslip-ux-review',checks:'grid defaults, share drafts, continuous typing, formatted paste sanitization, formatted copy, template save, responsive widths, typed deletion confirmation, focus trap, Escape and scroll restoration'}))
  assert.deepEqual(errors,[])
} finally { await browser.close() }
